# Break

for i in range(1, 11):
    if i == 5:
        break
    print(i)

# Continue -> to skip the current iteration

for i in range(1, 11):
    if i == 5:
        continue
    print(i)

# pass -> when you dont have logic or you want to come to the code back but you want to write the remaining code & not get any error then use 'pass'

for i in range(1,11):
    pass